/** A batch run that could not complete (HTTP error, a bot failure, a timeout). */
class BatchException(message: String, cause: Throwable? = null) : RuntimeException(message, cause)

/** What one race of a batch produced, all of it read back through the API. */
class RaceRun(
    val courseId: String,
    val seed: Long,
    val raceId: String,
    val detail: RaceDetail,
    val results: Classification,
    /** The replay as served (`Content-Encoding: gzip`), written as is to `<course>-<seed>.json.gz`. */
    val replayGzip: ByteArray,
    val replay: Replay,
    val bots: List<TeamBotResult>,
    /** Kernel-side count of the HTTP requests of this race (admin, bots, runner downloads; SSE connections count 1). */
    val httpRequests: Long,
    val wallMillis: Long,
) {
    val hash: String get() = resultHash(results.entries)
    /** Decision points of the race (every bot answers each of them once). */
    val decisions: Int get() = bots.maxOfOrNull { it.decisions } ?: 0
    val ordersSent: Int get() = bots.sumOf { it.ordersSent }
    val ordersRejected: Int get() = bots.sumOf { it.ordersRejected }
}

/**
 * Result hash (DESIGN §6): SHA-256 of the classification entries (rider, team, status, position, time, gap) in
 * the API's JSON. The race id is left out, so a run through the kernel and the calibration harness compare.
 */
fun resultHash(entries: List<ResultEntry>): String {
    val json = ApiJson.encodeToString(kotlinx.serialization.builtins.ListSerializer(ResultEntry.serializer()), entries)
    return MessageDigest.getInstance("SHA-256").digest(json.encodeToByteArray()).joinToString("") { "%02x".format(it) }
}

/**
 * The batch race runner (DESIGN §6): an embedded kernel on a free local port, and for each race 10 [TeamBot]s in
 * this process that only talk HTTP to it. The runner itself only uses the API too (admin token), except
 * [KernelServer] to start and stop the kernel and to wait for a race's end.
 */
class BatchRunner private constructor(
    val server: KernelServer,
    private val adminToken: String,
    private val engine: HttpClientEngine,
    private val requests: AtomicLong,
    private val botLog: (String) -> BotLogger,
    private val raceTimeout: Duration,
) : AutoCloseable {
    private val client = HttpClient(engine) {
        expectSuccess = false
        install(HttpTimeout) { requestTimeoutMillis = 60_000 }
        install(ContentNegotiation) { json(ApiJson) }
    }

    val baseUrl: String get() = server.baseUrl

    /**
     * Runs one lockstep race of [courseId] with [seed]: create, register the 10 generated teams (names and colors
     * from [RiderGenerator.teamIdentities], riders generated by the kernel), start the bots, wait for all their
     * streams, start, wait for the end, download results and replay. Strategy parameters are the harness's
     * [Calibration.teamParams], so a batch race and a calibration race of the same seed are the same race.
     */
    suspend fun runRace(courseId: String, seed: Long): RaceRun {
        val t0 = TimeSource.Monotonic.markNow()
        val before = requests.get()
        val raceId = post<CreateRaceResponse>(
            ApiPaths.races(), CreateRaceRequest(courseId, seed, ClockConfig(ClockMode.LOCKSTEP)), "create race",
        ).raceId
        val teams = RiderGenerator.teamIdentities(seed).map { t ->
            post<RegisterTeamResponse>(ApiPaths.raceTeams(raceId), RegisterTeamRequest(t.name, t.color), "register ${t.name}")
        }
        val params = Calibration.teamParams(seed, teams.map { it.teamId })
        val bots = teams.map { t ->
            TeamBot(TeamBotConfig(baseUrl, raceId, t.teamId, t.token, params.getValue(t.teamId)), engine, botLog(t.teamId))
        }
        val results: List<TeamBotResult> = try {
            withTimeout(raceTimeout) {
                coroutineScope {
                    val runs = bots.map { b -> async { b.run() } }
                    bots.forEach { it.connected.await() }
                    post<RaceDetail>(ApiPaths.raceStart(raceId), null, "start")
                    // A failing bot fails the scope (and cancels the others): the race would go on auto-acked.
                    runs.awaitAll()
                }
            }
        } catch (e: Exception) {
            throw BatchException("race $raceId ($courseId, seed $seed) failed: ${e.message}", e)
        }
        server.kernel.race(raceId)?.awaitFinish() ?: throw BatchException("race $raceId vanished from the kernel")

        val detail = get<RaceDetail>(ApiPaths.race(raceId), "race")
        val classification = get<Classification>(ApiPaths.raceResults(raceId), "results")
        if (!classification.final) throw BatchException("race $raceId: results are not final")
        val replayResponse = client.get(baseUrl + ApiPaths.raceReplay(raceId)) { header(HttpHeaders.AcceptEncoding, "gzip") }
        check(replayResponse, "replay")
        val gzip = replayResponse.bodyAsBytes()
        if (gzip.size < 2 || gzip[0] != 0x1f.toByte() || gzip[1] != 0x8b.toByte()) throw BatchException("race $raceId: replay is not gzip")
        val replay = GZIPInputStream(ByteArrayInputStream(gzip)).bufferedReader().use {
            ApiJson.decodeFromString(Replay.serializer(), it.readText())
        }
        return RaceRun(
            courseId, seed, raceId, detail, classification, gzip, replay, results,
            requests.get() - before, t0.elapsedNow().inWholeMilliseconds,
        )
    }

    private suspend inline fun <reified T> post(path: String, body: Any?, what: String): T {
        val response = client.post(baseUrl + path) {
            bearerAuth(adminToken)
            if (body != null) {
                contentType(ContentType.Application.Json)
                setBody(body)
            }
        }
        check(response, what)
        return response.body()
    }

    private suspend inline fun <reified T> get(path: String, what: String): T {
        val response = client.get(baseUrl + path)
        check(response, what)
        return response.body()
    }

    private suspend fun check(response: HttpResponse, what: String) {
        if (response.status != HttpStatusCode.OK && response.status != HttpStatusCode.Created) {
            throw BatchException("$what: ${response.status} ${response.bodyAsText().take(300)}")
        }
    }

    /** Stops the HTTP client and the kernel. Not called with `--serve`. */
    override fun close() {
        client.close()
        engine.close()
        server.stop()
    }

    companion object {
        /**
         * The embedded kernel's default seed secret ([KernelConfig.seedSecret]): fixed, so a batch is reproducible
         * from its seed (`UCAI_SEED_SECRET` overrides it). Pass the same secret to [Calibration.run] to rerun a race.
         */
        const val SEED_SECRET = "ucai-batch-runner"

        /**
         * Starts the embedded kernel on [port] (0: a free one) with [courses]. Bots log WARN and ERROR through
         * [log]; the kernel logs through [kernelLog].
         */
        suspend fun start(
            courses: List<Course>,
            adminToken: String,
            port: Int = 0,
            host: String = "127.0.0.1",
            log: (String) -> Unit = ::println,
            kernelLog: KernelLog = KernelLog.DEFAULT,
            raceTimeout: Duration = 10.minutes,
            wallClock: (() -> String)? = null,
            seedSecret: String = SEED_SECRET,
        ): BatchRunner {
            val requests = AtomicLong()
            val counter = createApplicationPlugin("RequestCounter") { onCall { requests.incrementAndGet() } }
            val server = startKernelServer(
                KernelConfig(adminToken, CourseCatalog.of(courses), log = kernelLog, wallClock = wallClock, seedSecret = seedSecret),
                port, host,
            ) { install(counter) }
            // One client engine for the runner and the 10 bots; no engine-level timeout (the streams have none).
            val engine = CIO.create { requestTimeout = 0 }
            val botLog = { teamId: String -> BotLogger { level, message -> if (level >= LogLevel.WARN) log("  [$teamId] $level $message") } }
            return BatchRunner(server, adminToken, engine, requests, botLog, raceTimeout)
        }
    }
}
